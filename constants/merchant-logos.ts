// Try to find a canonical key for a merchant name.
export function findMerchantLogoKey(
  merchantName?: string | null,
): string | null {
  if (!merchantName) return null;

  const n = normalizeMerchantName(merchantName);

  // Direct alias match
  if (CANONICAL_ALIASES[n]) return CANONICAL_ALIASES[n];

  // Exact match to alias key
  if (Object.prototype.hasOwnProperty.call(CANONICAL_ALIASES, n))
    return CANONICAL_ALIASES[n];

  // Substring match (safe partial matching): only match if token is at start or full token
  const tokens = n.split("-").filter(Boolean);
  for (const token of tokens) {
    if (CANONICAL_ALIASES[token]) return CANONICAL_ALIASES[token];
    if (ASSETS[token]) return token;
  }

  // Try fuzzy-ish match: if any canonical key is contained in the normalized string
  for (const key of Object.keys(CANONICAL_ALIASES)) {
    if (n.includes(key)) return CANONICAL_ALIASES[key];
  }

  // Finally, if we have an asset whose key matches a substring
  for (const key of Object.keys(ASSETS)) {
    if (n.includes(key)) return key;
  }

  return null;
}

export function getMerchantLogoAsset(merchantName?: string | null) {
  const key = findMerchantLogoKey(merchantName);
  if (!key) return null;
  return ASSETS[key] ?? null;
}

export default {
  normalizeMerchantName,
  findMerchantLogoKey,
  getMerchantLogoAsset,
  ASSETS,
};


#!/usr/bin/env node
const fs = require("fs");
const path = require("path");

// Configuration
const ROOT = path.join(__dirname, "..");
const ASSETS_DIR = path.join(ROOT, "assets", "merchant-logos");
const TARGET_FILE = path.join(ROOT, "constants", "merchant-logos.ts");
const START_MARKER = "/* AUTO-GENERATED-MERCHANT-LOGOS:START */";
const END_MARKER = "/* AUTO-GENERATED-MERCHANT-LOGOS:END */";

const SUPPORTED_EXTS = [".png", ".jpg", ".jpeg", ".webp", ".gif"];

function toCamelCaseIdentifier(name) {
  // Remove extension and trim
  const base = name.replace(/\.[^.]+$/, "");
  // Split on non-alphanumeric characters and underscores/spaces
  const tokens = base.split(/[^a-zA-Z0-9]+/).filter(Boolean);
  if (tokens.length === 0) return "_image";
  const parts = tokens.map((t) => t.replace(/[^a-zA-Z0-9]/g, ""));
  const first = parts[0].toLowerCase();
  const rest = parts
    .slice(1)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1).toLowerCase());
  let id = first + rest.join("");
  // Ensure identifier starts with a letter or underscore
  if (!/^[a-zA-Z_]/.test(id)) id = "_" + id;
  // Remove any left-over invalid characters
  id = id.replace(/[^a-zA-Z0-9_]/g, "");
  return id;
}

function toLookupKey(name) {
  // Remove extension, normalize spaces, lower-case
  const base = name.replace(/\.[^.]+$/, "");
  const tokens = base.split(/[^a-zA-Z0-9]+/).filter(Boolean);
  return tokens.map((t) => t.toLowerCase()).join(" ");
}

function generate() {
  if (!fs.existsSync(ASSETS_DIR)) {
    console.error("Assets directory not found:", ASSETS_DIR);
    process.exit(1);
  }

  const files = fs.readdirSync(ASSETS_DIR).filter((f) => {
    const ext = path.extname(f).toLowerCase();
    return SUPPORTED_EXTS.includes(ext);
  });

  // Sort alphabetically by filename (case-insensitive)
  files.sort((a, b) => a.toLowerCase().localeCompare(b.toLowerCase()));

  const imports = [];
  const entries = [];
  const seenKeys = new Set();
  const usedVars = new Set();

  for (const filename of files) {
    const varBase = toCamelCaseIdentifier(filename);
    let varName = varBase;
    let suffix = 1;
    while (usedVars.has(varName)) {
      varName = `${varBase}${suffix}`;
      suffix += 1;
    }
    usedVars.add(varName);

    const importPath = `../assets/merchant-logos/${filename}`;
    const key = toLookupKey(filename);
    if (seenKeys.has(key)) {
      console.warn(
        `Skipping duplicate lookup key for filename '${filename}' (key='${key}').`,
      );
      continue;
    }
    seenKeys.add(key);

    imports.push({ varName, filename, importPath });
    entries.push({ key, varName });
  }

  const importLines = imports.map(
    (imp) => `import ${imp.varName} from "${imp.importPath}";`,
  );

  const entryLines = entries.map((e) => `  "${e.key}": ${e.varName},`);

  const generatedBlock = [];
  generatedBlock.push(START_MARKER);
  generatedBlock.push(
    "// This block is auto-generated by scripts/generate-merchant-logos.js",
  );
  generatedBlock.push(
    "// Do not edit the lines between the START/END markers manually — they will be overwritten.",
  );
  generatedBlock.push("");
  generatedBlock.push(...importLines);
  generatedBlock.push("");
  generatedBlock.push("export const MERCHANT_LOGOS: Record<string, any> = {");
  generatedBlock.push(...entryLines);
  generatedBlock.push("};");
  generatedBlock.push("");
  generatedBlock.push(END_MARKER);

  const genText = generatedBlock.join("\n");

  if (!fs.existsSync(TARGET_FILE)) {
    // Create a new file with the generated block
    const header = `// Merchant logos registry (auto-managed)\n\n`;
    fs.writeFileSync(TARGET_FILE, header + genText + "\n", "utf8");
    console.log("Created", TARGET_FILE);
    return;
  }

  // If exists, replace only the auto-generated section if present
  let content = fs.readFileSync(TARGET_FILE, "utf8");
  const start = content.indexOf(START_MARKER);
  const end = content.indexOf(END_MARKER);
  if (start !== -1 && end !== -1 && end > start) {
    const before = content.slice(0, start);
    const after = content.slice(end + END_MARKER.length);
    const newContent = before + genText + after;
    fs.writeFileSync(TARGET_FILE, newContent, "utf8");
    console.log("Updated auto-generated section in", TARGET_FILE);
  } else {
    // Append at the end
    content = content + "\n\n" + genText + "\n";
    fs.writeFileSync(TARGET_FILE, content, "utf8");
    console.log("Appended auto-generated section to", TARGET_FILE);
  }
}

generate();
